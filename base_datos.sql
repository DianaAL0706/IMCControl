-- Tabla de usuarios
CREATE TABLE USUARIOS (
    ID_USUARIO INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOMBRE_COMPLETO VARCHAR(100) NOT NULL,
    EDAD INT NOT NULL,
    SEXO VARCHAR(20) NOT NULL,
    ESTATURA DOUBLE NOT NULL,
    NOMBRE_USUARIO VARCHAR(50) NOT NULL UNIQUE,
    CONTRASENA_HASH VARCHAR(255) NOT NULL,
    CONSTRAINT CHK_EDAD CHECK (EDAD >= 15),
    CONSTRAINT CHK_ESTATURA CHECK (
        ESTATURA >= 1.0 AND ESTATURA <= 2.5
    )
);

-- Tabla de registros de IMC
CREATE TABLE REGISTROS_IMC (
    ID_REGISTRO INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    PESO DOUBLE NOT NULL,
    ESTATURA DOUBLE NOT NULL,
    IMC DOUBLE NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_PESO CHECK (PESO > 0),
    CONSTRAINT CHK_ESTATURA_IMC CHECK (
        ESTATURA >= 1.0 AND ESTATURA <= 2.5
    ),
    CONSTRAINT FK_USUARIO_IMC FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS(ID_USUARIO)
);

